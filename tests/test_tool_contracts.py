def _first_tool_with_properties(schemas: Mapping[str, Any]) -> tuple[str, str]:
    for name, schema in sorted(schemas.items()):
        if isinstance(schema, dict) and schema.get("properties"):
            return name, sorted(schema["properties"])[0]
    raise AssertionError("no frozen output schema has properties")


class TestOutputSchemaDiff:
    def test_renamed_property_names_the_tool_and_both_paths(self, frozen):
        tool, prop = _first_tool_with_properties(frozen)
        mutated = copy.deepcopy(frozen)
        properties = mutated[tool]["properties"]
        properties[prop + "_renamed"] = properties.pop(prop)

        drifts = diff_output_schemas(frozen, mutated)

        assert {d.tool for d in drifts} == {tool}
        located = {d.path: d.problem for d in drifts}
        assert set(located) == {
            f"/properties/{prop}",
            f"/properties/{prop}_renamed",
        }
        assert "not in the fixture" in located[f"/properties/{prop}"]
        assert "not listed" in located[f"/properties/{prop}_renamed"]

    def test_changed_value_is_located(self, frozen):
        tool, prop = _first_tool_with_properties(frozen)
        mutated = copy.deepcopy(frozen)
        mutated[tool]["properties"][prop]["description"] = "frozen wording"

        drifts = diff_output_schemas(frozen, mutated)

        assert [(d.tool, d.path) for d in drifts] == [
            (tool, f"/properties/{prop}/description")
        ]
        assert "frozen wording" in drifts[0].problem

    def test_fixture_missing_a_tool_is_reported(self, frozen):
        dropped = sorted(frozen)[0]
        mutated = {name: s for name, s in frozen.items() if name != dropped}

        drifts = diff_output_schemas(frozen, mutated)

        assert [(d.tool, d.path) for d in drifts] == [(dropped, "")]
        assert "not in the fixture" in drifts[0].problem

    def test_fixture_with_an_extra_tool_is_reported(self, frozen):
        mutated = {**frozen, "ghost_tool": {"type": "object"}}

        drifts = diff_output_schemas(frozen, mutated)

        assert [(d.tool, d.path) for d in drifts] == [("ghost_tool", "")]
        assert "not listed" in drifts[0].problem

    def test_schema_no_longer_advertised_is_reported(self, frozen):
        tool, _ = _first_tool_with_properties(frozen)
        listed = {**frozen, tool: None}

        drifts = diff_output_schemas(listed, frozen)

        assert [(d.tool, d.path) for d in drifts] == [(tool, "")]


class TestNameParity:
    def test_mismatch_names_both_tools_and_both_sides(self):
        violations = name_parity(
            ["shared", "only_public"], {PRIVATE_SIDE: ["shared", "only_private"]}
        )

        assert sorted(violations) == [
            ParityViolation("only_private", PRIVATE_SIDE, PUBLIC_SIDE),
            ParityViolation("only_public", PUBLIC_SIDE, PRIVATE_SIDE),
        ]

    def test_moved_private_registry_is_a_parity_failure(self):
        """An SDK that drops ``_tool_manager`` empties the private side, and
        every public name is then reported against it."""
        violations = name_parity(
            ["analyze_fft"], {PRIVATE_SIDE: private_tool_names(object())}
        )

        assert violations == [ParityViolation("analyze_fft", PUBLIC_SIDE, PRIVATE_SIDE)]


class TestDescriptionCheck:
    def test_empty_descriptions_fail(self):
        listing = [
            {"name": "summarised", "description": "\n    Summary line.\n\n    More."},
            {"name": "blank", "description": " \n\n  "},
            {"name": "absent"},
        ]

        assert description_violations(listing) == ["absent", "blank"]
