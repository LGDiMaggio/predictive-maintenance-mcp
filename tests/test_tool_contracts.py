class TestRealSurface:
    """The listing a host receives passes every contract check."""

    def test_listing_is_not_trivially_small(self, listing):
        assert len(listing) >= MIN_TOOLS

    def test_public_names_match_registry_and_inventory(self, server, listing):
        violations = name_parity(
            [tool["name"] for tool in listing],
            {
                PRIVATE_SIDE: private_tool_names(server),
                INVENTORY_SIDE: load_inventory(INVENTORY),
            },
        )
        assert violations == [], "tool name parity broken:\n" + _report(violations)

    def test_every_schema_is_valid_json_schema(self, listing):
        violations = check_tool_schemas(listing)
        assert violations == [], "invalid tool schemas:\n" + _report(violations)

    def test_output_schemas_match_the_fixture(self, listing, frozen):
        listed = output_schemas(listing)
        drifts = diff_output_schemas(listed, frozen)
        assert drifts == [], (
            "output schemas drifted from tests/fixtures/tool_output_schemas.json "
            "(regenerate on purpose, see the module docstring):\n"
            + _report(f"{d.tool} {d.path or '<root>'}: {d.problem}" for d in drifts)
        )
        assert len(set(listed) & set(frozen)) >= MIN_TOOLS

    def test_every_tool_has_a_first_description_line(self, listing):
        assert description_violations(listing) == []


