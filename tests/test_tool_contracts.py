"""Tool contracts as a client sees them: names, schemas and output shapes.

The older surface guards (``test_tool_inventory``, ``test_error_contract``,
``test_surface_parity``) read ``mcp._tool_manager._tools``, a private SDK
attribute. This module lists the tools the way a host does, through
``Client(mcp, mode="legacy").list_tools()``, and checks four things:

* the public names equal both the private registry and the frozen inventory
  (``tests/fixtures/tool_inventory.json``). If an SDK release moves the
  private registry, that shows up here as an explicit parity failure naming
  both sides, not as a silently empty loop in the older guards;
* every input and output schema is a valid JSON Schema 2020-12 document
  (``tools.audit.mcp_smoke.check_tool_schemas``, shared with the stdio
  smoke harness);
* every output schema equals the frozen one in
  ``tests/fixtures/tool_output_schemas.json``;
* every tool has a non-empty first description line. Leading blank lines
  from raw docstrings are tolerated; description quality stays with
  issue #53.

Why output schemas are frozen
-----------------------------
The tools return typed models, so ``tools/list`` advertises an
``outputSchema`` for each one and every result travels as
``structuredContent`` that conforms to it. Hosts and models read those field
names and types. Renaming a property, changing a type, or losing the schema
altogether (mcp 2.1+ stops advertising one for tools annotated to return
content blocks) is a protocol-visible change, as visible as an input-schema
change. ``test_tool_inventory`` deliberately left output models unfrozen
while U6 and U9 reshaped them; the surface has been stable since, and this
fixture closes that gap.

The schemas are generated by pydantic, so a pydantic or SDK release can
change them without any edit here. The fixture is generated in the locked
environment (``uv.lock``); a difference under a newer resolution is the drift
the weekly audit exists to surface, not a reason to regenerate from whatever
happens to be installed.

Fixture format: ``{tool name: outputSchema or null}`` as canonical JSON
(sorted keys, indent 2, ASCII, LF line endings, trailing newline). Never edit
it by hand.

Regeneration recipe (run from the repo root with the interpreter of an
environment installed from ``uv.lock``; ``import tests.conftest`` pins the
package import to this checkout, which a worktree sharing the primary venv
would otherwise miss):
    python -c "import tests.conftest; \\
               from tests.test_tool_contracts import write_fixture; \\
               write_fixture()"

Fixture history:
- Initial snapshot (2026-10-15): 38 tools, every one with an outputSchema.
  Generated under mcp 2.0.0 and pydantic 2.12.0 (uv.lock); identical under
  mcp 2.3.0 and pydantic 2.14.1.
- Re-processing progress (2026-10-19): regenerated intentionally: ADDITIVE,
  no shape changed. Four descriptions rewritten: assess_asset_change
  reprocess (the block's keys and how a sequence is followed) and remedy
  (the call, or the actions that close the gap), and declare_measurement_point
  root description and remedy (the call only when one can act). Each states
  the stop rule, including when a new sequence starts. The reprocess
  description names each failure's action_id and the needs_action actions
  that give each text once. Generated under mcp 2.3.0 and pydantic 2.12.0
  (uv.lock).
- Bearing check outcome (2026-10-20, #84): regenerated intentionally:
  ADDITIVE, no shape changed. diagnose_vibration gains the required
  bearing_check block (BearingCheckOutcome: status, reason_code, reason,
  remedy); the bearing_faults and evidence_strength descriptions name it.
  Generated under mcp 2.3.0 and pydantic 2.12.0 (uv.lock).
"""

from __future__ import annotations

import copy
import json
from collections.abc import Iterable, Iterator, Mapping
from pathlib import Path
from typing import Any, NamedTuple

import anyio
import pytest
from mcp import Client
from mcp.server.mcpserver import MCPServer

from predictive_maintenance_mcp.mcp_tools import register_all
from tools.audit.mcp_smoke import (
    check_tool_schemas,
    diff_inventory,
    list_all_tools,
    load_inventory,
)

FIXTURES = Path(__file__).parent / "fixtures"
FIXTURE = FIXTURES / "tool_output_schemas.json"
INVENTORY = FIXTURES / "tool_inventory.json"

#: Anti-rot floor: a listing or comparison smaller than this means the
#: harness stopped seeing the surface, not that the surface shrank.
MIN_TOOLS = 30

PUBLIC_SIDE = "public tools/list"
PRIVATE_SIDE = "private _tool_manager._tools"
INVENTORY_SIDE = "tests/fixtures/tool_inventory.json"


# ---------------------------------------------------------------------------
# Pure parts
# ---------------------------------------------------------------------------


class ParityViolation(NamedTuple):
    """A tool name present on one side and absent from the other."""

    tool: str
    present_in: str
    absent_from: str


class SchemaDrift(NamedTuple):
    """One output-schema difference: tool, JSON pointer ("" = root), what."""

    tool: str
    path: str
    problem: str


def name_parity(
    public: Iterable[str], others: Mapping[str, Iterable[str]]
) -> list[ParityViolation]:
    """Two-way name difference between the public listing and each other side.

    Args:
        public: Tool names from ``tools/list``.
        others: Side label -> tool names on that side.

    Returns:
        One violation per name missing from a side, naming both sides.
    """
    public = list(public)
    violations: list[ParityViolation] = []
    for side, names in others.items():
        diff = diff_inventory(discovered=public, expected=names)
        violations.extend(
            ParityViolation(name, PUBLIC_SIDE, side) for name in diff["unexpected"]
        )
        violations.extend(
            ParityViolation(name, side, PUBLIC_SIDE) for name in diff["missing"]
        )
    return violations


def _pointer_token(key: str) -> str:
    """RFC 6901 escaping of one JSON pointer reference token."""
    return key.replace("~", "~0").replace("/", "~1")


def _brief(value: Any) -> str:
    text = json.dumps(value, sort_keys=True)
    return text if len(text) <= 80 else text[:77] + "..."


def _diff_json(listed: Any, frozen: Any, path: str) -> Iterator[tuple[str, str]]:
    if isinstance(listed, dict) and isinstance(frozen, dict):
        for key in sorted(set(listed) | set(frozen)):
            child = f"{path}/{_pointer_token(key)}"
            if key not in frozen:
                yield child, f"listed but not in the fixture: {_brief(listed[key])}"
            elif key not in listed:
                yield child, f"in the fixture but not listed: {_brief(frozen[key])}"
            else:
                yield from _diff_json(listed[key], frozen[key], child)
    elif isinstance(listed, list) and isinstance(frozen, list):
        for index in range(max(len(listed), len(frozen))):
            child = f"{path}/{index}"
            if index >= len(frozen):
                yield child, f"listed but not in the fixture: {_brief(listed[index])}"
            elif index >= len(listed):
                yield child, f"in the fixture but not listed: {_brief(frozen[index])}"
            else:
                yield from _diff_json(listed[index], frozen[index], child)
    # type() as well as ==: JSON true, 1 and 1.0 are different values.
    elif type(listed) is not type(frozen) or listed != frozen:
        yield path, f"listed {_brief(listed)}, fixture {_brief(frozen)}"


def diff_output_schemas(
    listed: Mapping[str, Any], frozen: Mapping[str, Any]
) -> list[SchemaDrift]:
    """Two-way difference between listed and frozen output schemas.

    Args:
        listed: Tool name -> ``outputSchema`` (None when not advertised).
        frozen: The same mapping as stored in the fixture.

    Returns:
        A tool missing from either side, and every added, removed or changed
        value inside a tool's schema, located by JSON pointer.
    """
    drifts: list[SchemaDrift] = []
    for name in sorted(set(listed) | set(frozen)):
        if name not in frozen:
            drifts.append(SchemaDrift(name, "", "tool listed but not in the fixture"))
        elif name not in listed:
            drifts.append(SchemaDrift(name, "", "tool in the fixture but not listed"))
        else:
            drifts.extend(
                SchemaDrift(name, path, problem)
                for path, problem in _diff_json(listed[name], frozen[name], "")
            )
    return drifts


def description_violations(tools: Iterable[Mapping[str, Any]]) -> list[str]:
    """Names of tools whose description has no non-empty first line.

    Leading blank lines (raw docstrings start with a newline) are skipped:
    the first line a host shows is the first non-blank one.
    """
    return sorted(
        str(tool.get("name"))
        for tool in tools
        if not (tool.get("description") or "").strip()
    )


# ---------------------------------------------------------------------------
# The server as a client sees it
# ---------------------------------------------------------------------------


def build_server() -> MCPServer:
    """A freshly registered in-process server."""
    mcp = MCPServer("tool-contracts")
    register_all(mcp)
    return mcp


async def _list_pages(mcp: MCPServer) -> list[dict[str, Any]]:
    async with Client(mcp, mode="legacy") as client:
        tools = await list_all_tools(client)
    return [
        tool.model_dump(mode="json", by_alias=True, exclude_none=True) for tool in tools
    ]


def list_public_tools(mcp: MCPServer) -> list[dict[str, Any]]:
    """Every tool from ``tools/list``, in wire shape (camelCase keys)."""
    return anyio.run(_list_pages, mcp)


def private_tool_names(mcp: Any) -> set[str]:
    """Names in the SDK's private registry; empty when it is not where the
    older guards expect it, so the parity check reports every public name."""
    registry = getattr(getattr(mcp, "_tool_manager", None), "_tools", None)
    if not isinstance(registry, Mapping):
        return set()
    return {tool.name for tool in registry.values()}


def output_schemas(tools: Iterable[Mapping[str, Any]]) -> dict[str, Any]:
    """Tool name -> advertised ``outputSchema`` (None when absent)."""
    return {tool["name"]: tool.get("outputSchema") for tool in tools}


def canonical_json(value: Any) -> str:
    """Sorted keys, indent 2, ASCII, trailing newline."""
    return json.dumps(value, indent=2, sort_keys=True) + "\n"


def write_fixture(path: Path = FIXTURE) -> None:
    """Regenerate the output-schema fixture (see the module docstring)."""
    schemas = output_schemas(list_public_tools(build_server()))
    # Bytes, not write_text: Windows would translate "\n" into CRLF.
    path.write_bytes(canonical_json(schemas).encode("ascii"))


def _report(lines: Iterable[Any]) -> str:
    return "\n".join(f"  {line}" for line in lines)


